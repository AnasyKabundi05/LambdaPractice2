public class GenericCountClass <String, Integer>{

    private String count;
    private Integer number;

    public GenericCountClass(){
        this.count = count;
        this.number = number;
    }

    public String getCount() {
        return count;
    }

    public Integer getNumber() {
        return number;
    }

    public void setCount(String count) {
        this.count = count;
    }

    public void setNumber(Integer number) {
        this.number = number;
    }
}
